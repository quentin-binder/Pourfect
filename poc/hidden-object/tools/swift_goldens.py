"""Golden data for the app's HiddenCore (Swift) port of the placement and blending rules.

Usage: python swift_goldens.py <HiddenScenes dir> <out json>   (needs Pillow + numpy; Python 3.9 random)
Replays tools/layout.py for a few seeds on the app export (HiddenScenes/<scene>/scene.json, the exported
object sizes and background.jpg) by calling layout.py's own `pick` and `render_size` and hocommon.py's
`match_to_scene` and `occluder_from_polygon`, with the same random-number sequence as layout.py's main():
sample + shuffle in pick, then per object (back to front) render size, flip, tint strength.
Also records raw `random.Random` outputs so the Swift Mersenne Twister can be checked on its own.
"""
import json, random, sys
from pathlib import Path
import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from layout import pick, render_size          # noqa: E402  (the rules under test)
from hocommon import match_to_scene, shadow_for, occluder_from_polygon  # noqa: E402

SEEDS = [1, 2, 7]
COUNT = 12
SAMPLES = [(200, 40, 40), (30, 160, 90), (240, 220, 180), (10, 10, 10), (128, 128, 128)]


class Sized:
    """Stands in for a PIL image in render_size (it only reads .size)."""
    def __init__(self, size): self.size = tuple(size)


def scene_goldens(root, scene):
    d = json.loads((root / scene / "scene.json").read_text())
    bg = Image.open(root / scene / "background.jpg").convert("RGBA")
    W, H = bg.size
    lib = [{"id": o["id"], "name": o["name"], "size": o["sizeClass"], "px": o["size"]} for o in d["objects"]]
    out = []
    for seed in SEEDS:
        rng = random.Random(seed)
        chosen = pick(lib, d["spots"], COUNT, rng)
        rows = []
        for o, s in sorted(chosen, key=lambda c: c[1]["y"]):
            L = render_size(Sized(o["px"]), o["size"], s, rng)
            k = L / max(o["px"])
            w, h = max(1, round(o["px"][0] * k)), max(1, round(o["px"][1] * k))
            flip = rng.random() < 0.3
            x, y = s["x"] - w // 2, s["y"] - h
            t = rng.uniform(0.18, 0.26)
            pad = max(w, h)
            box = [max(0, x - pad), max(0, y - pad), min(W, x + w + pad), min(H, y + h + pad)]
            region = np.array(bg.crop(box).convert("RGB")).reshape(-1, 3).astype(np.float32)
            mean = [float(v) for v in region.mean(0)]
            samples = []
            for c in SAMPLES:
                px = Image.new("RGBA", (1, 1), c + (255,))
                r = match_to_scene(px, bg, (x, y, w, h), t).getpixel((0, 0))
                samples.append([list(c), list(r[:3])])
            ow, oh = w, h
            sh, spad = shadow_for(Image.new("RGBA", (ow, oh), (0, 0, 0, 255)), 0.38)
            row = {"object": o["id"], "spot": s["id"], "longSide": L, "w": w, "h": h, "flip": flip,
                   "x": x, "y": y, "tint": t, "tintBox": box, "mean": mean, "samples": samples,
                   "shadow": [x - spad + 5, y - spad + 4, sh.width, sh.height]}
            if "occlusion" in s:
                patch, (px0, py0) = occluder_from_polygon(bg, s["occlusion"]["polygon"], s["occlusion"]["feather"])
                a = np.array(patch)[..., 3]
                row["occluder"] = {"x": px0, "y": py0, "w": patch.width, "h": patch.height,
                                   "rows": [int(v) for v in a[:, 0]],
                                   "uniformColumns": bool((a == a[:, :1]).all())}
            rows.append(row)
        out.append({"scene": scene, "seed": seed, "count": COUNT, "placements": rows})
    return out


def random_goldens():
    r = random.Random(1)
    first = [r.random() for _ in range(5)]
    r = random.Random(123456789012)
    bits = [r.getrandbits(k) for k in (1, 5, 13, 32)]
    r = random.Random(42)
    shuffled = list(range(20)); r.shuffle(shuffled)
    sample_pool = r.sample(list(range(40)), 12)
    sample_set = r.sample(list(range(200)), 4)
    uni = r.uniform(0.88, 1.0)
    r = random.Random(0)
    zero = [r.random() for _ in range(2)]
    r = random.Random(2 ** 40 + 5)
    big = [r.random() for _ in range(2)]
    return {"seed1_random": first, "seed123456789012_bits_1_5_13_32": bits, "seed42_shuffle20": shuffled,
            "seed42_then_sample40_12": sample_pool, "seed42_then_sample200_4": sample_set,
            "seed42_then_uniform": uni, "seed0_random": zero, "seed2p40p5_random": big}


if __name__ == "__main__":
    root, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    doc = {"note": "generated by poc/hidden-object/tools/swift_goldens.py; do not edit",
           "random": random_goldens(),
           "layouts": [g for s in ("attic", "market", "hoard") for g in scene_goldens(root, s)]}
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(doc, indent=0))
    print("wrote", out_path, len(doc["layouts"]), "layouts")
